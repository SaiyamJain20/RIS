#!/usr/bin/env python3
"""Build complete launch prompts from shared context and each agent's role."""

import argparse
import hashlib
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report stale prompts without writing files")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    common = (directory / "COMMON_AGENT_CONTEXT.md").read_text(encoding="utf-8")
    names = {1: "Ledger and policy", 2: "Protocol and key services", 3: "Evaluation and integration"}
    stale = []
    for number, name in names.items():
        role_path = directory / f"agent-{number}" / "ROLE.md"
        role = role_path.read_text(encoding="utf-8")
        common_hash = hashlib.sha256(common.encode("utf-8")).hexdigest()
        role_hash = hashlib.sha256(role.encode("utf-8")).hexdigest()
        prompt = (
            f"# Complete launch prompt — agent {number}: {name}\n\n"
            f"You are agent {number}. This is your complete assignment; the common rules and your specific role are included below. "
            "You need no earlier chat context. Work from the live repository and current board.\n\n"
            "> Launch: paste this entire file into the assigned agent session, or explicitly instruct the agent to read and execute this file as its assignment. "
            "The human-supplied assignment includes the scoped implementation and coordinator Git authorization described below.\n\n"
            "<!-- Generated by communication/build_prompts.py. Edit COMMON_AGENT_CONTEXT.md or ROLE.md, then rebuild.\n"
            f"Common-SHA256: {common_hash}\nRole-SHA256: {role_hash}\n-->\n\n"
            f"{common.rstrip()}\n\n---\n\n{role.rstrip()}\n"
        )
        output = role_path.with_name("START_PROMPT.md")
        current = output.read_text(encoding="utf-8") if output.exists() else None
        if current != prompt:
            if args.check:
                stale.append(str(output.relative_to(directory.parent)))
            else:
                output.write_text(prompt, encoding="utf-8")
                print(f"Built {output.relative_to(directory.parent)}")
    if stale:
        print("Stale or missing complete prompts:\n" + "\n".join(stale))
        return 1
    if args.check:
        print("All three complete launch prompts match the common context and role sources.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
